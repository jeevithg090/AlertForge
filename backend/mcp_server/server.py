def read_runbook(path: str) -> str:
    base = os.environ.get("RUNBOOKS_DIR", "/runbooks")
    full = os.path.join(base, path.replace("runbooks/", ""))
    try:
        with open(full) as f:
            return f.read()
    except FileNotFoundError:
        return f"# Runbook not found: {path}\n\nThis runbook has not been indexed yet."


def create_jira_ticket(summary: str, description: str, priority: str = "Medium", project: str = "SEC") -> dict:
    """Stub JIRA ticket creation.

    In production this would call the Atlassian REST API (
    POST /rest/api/3/issue) with an API token. For the demo we synthesize a
    believable, deterministic-looking ticket id + a real-looking Cloud JIRA URL.
    """
    ticket_id = f"{project}-{uuid.uuid4().hex[:6].upper()}"
    return {
        "ticket_id": ticket_id,
        "summary": summary[:200],
        "description": description[:2000],
        "priority": priority,
        "status": "Open",
        "url": f"https://sentinelforge.atlassian.net/browse/{ticket_id}",
        "created_at": datetime.now(UTC).isoformat(),
        "type": "Security Incident",
        "assignee": "unassigned@sentinelforge.io",
        "labels": [" autogenerated-by-sentinelforge", "soc", "ai-triaged"],
    }


def update_jira_ticket(ticket_id: str, status: str = "", comment: str = "") -> dict:
    return {
        "ticket_id": ticket_id,
        "status": status or "In Progress",
        "comment_added": bool(comment),
        "updated_at": datetime.now(UTC).isoformat(),
    }


# ---------- MCP SDK server ----------

if HAS_MCP_SDK:
    server = Server("sentinelforge-mcp")

    TOOLS = [
        Tool(
            name="search_runbooks",
            description="Search the engineering runbook knowledge base for troubleshooting procedures.",
            inputSchema={
                "type": "object",
                "properties": {
                    "query": {"type": "string", "description": "Natural language search query"},
                    "top_k": {"type": "integer", "default": 3},
                },
                "required": ["query"],
            },
        ),
        Tool(
            name="read_runbook",
            description="Read the full content of a specific runbook by its path.",
            inputSchema={
                "type": "object",
                "properties": {"path": {"type": "string"}},
                "required": ["path"],
            },
        ),
        Tool(
            name="create_jira_ticket",
            description="Create a new JIRA incident ticket.",
            inputSchema={
                "type": "object",
                "properties": {
                    "summary": {"type": "string"},
                    "description": {"type": "string"},
                    "priority": {"type": "string", "enum": ["Critical", "High", "Medium", "Low"]},
                    "project": {"type": "string", "default": "INC"},
                },
                "required": ["summary", "description"],
            },
        ),
        Tool(
            name="update_jira_ticket",
            description="Update an existing JIRA ticket status or add a comment.",
            inputSchema={
                "type": "object",
                "properties": {
                    "ticket_id": {"type": "string"},
                    "status": {"type": "string"},
                    "comment": {"type": "string"},
                },
                "required": ["ticket_id"],
            },
        ),
    ]

    @server.list_tools()
    async def list_tools():
        return TOOLS

    @server.call_tool()
    async def call_tool(name: str, arguments: dict):
        if name == "search_runbooks":
            result = search_runbooks(arguments.get("query", ""), arguments.get("top_k", 3))
        elif name == "read_runbook":
            result = read_runbook(arguments.get("path", ""))
        elif name == "create_jira_ticket":
            result = create_jira_ticket(
                arguments.get("summary", ""),
                arguments.get("description", ""),
                arguments.get("priority", "Medium"),
                arguments.get("project", "INC"),
            )
        elif name == "update_jira_ticket":
            result = update_jira_ticket(
                arguments.get("ticket_id", ""),
                arguments.get("status", ""),
                arguments.get("comment", ""),
            )
        else:
            result = {"error": f"unknown tool: {name}"}
        return [TextContent(type="text", text=json.dumps(result, default=str))]

    async def run_sdk_server():
        import uvicorn
        from starlette.applications import Starlette
        from starlette.routing import Route

        sse = SseServerTransport("/messages")

        async def handle_sse(request):
            async with sse.connect_sse(request.scope, request.receive, request._send) as streams:
                await server.run(streams[0], streams[1], server.create_initialization_options())

        async def handle_messages(request):
            await sse.handle_post_message(request.scope, request.receive, request._send)

        app = Starlette(routes=[
            Route("/sse", endpoint=handle_sse),
            Route("/messages", endpoint=handle_messages, methods=["POST"]),
        ])
        config = uvicorn.Config(app, host="0.0.0.0", port=8001)
        srv = uvicorn.Server(config)
        await srv.serve()


# ---------- FastAPI fallback ----------

async def run_fastapi_fallback():
    """Fallback MCP-like SSE server using FastAPI when mcp SDK is unavailable."""
    import asyncio

    import uvicorn
    from fastapi import FastAPI
    from fastapi.responses import JSONResponse
    from sse_starlette.sse import EventSourceResponse

    app = FastAPI(title="SentinelForge MCP Server (Fallback)")

    @app.get("/sse")
    async def sse_endpoint():
        async def event_generator():
            yield {"event": "endpoint", "data": "/messages"}
            while True:
                await asyncio.sleep(30)
                yield {"event": "ping", "data": ""}
        return EventSourceResponse(event_generator())

    @app.post("/messages")
    async def messages_endpoint(request_body: dict):
        method = request_body.get("method", "")
        params = request_body.get("params", {})
        if method == "tools/list":
            return JSONResponse({"result": {"tools": [
                {"name": "search_runbooks", "description": "Search runbooks", "inputSchema": {"type": "object", "properties": {"query": {"type": "string"}}}},
                {"name": "read_runbook", "description": "Read a runbook", "inputSchema": {"type": "object", "properties": {"path": {"type": "string"}}}},
                {"name": "create_jira_ticket", "description": "Create JIRA ticket", "inputSchema": {"type": "object", "properties": {"summary": {"type": "string"}, "description": {"type": "string"}}}},
                {"name": "update_jira_ticket", "description": "Update JIRA ticket", "inputSchema": {"type": "object", "properties": {"ticket_id": {"type": "string"}}}},
            ]}})
        elif method == "tools/call":
            name = params.get("name", "")
            args = params.get("arguments", {})
            if name == "search_runbooks":
                result = search_runbooks(args.get("query", ""), args.get("top_k", 3))
            elif name == "read_runbook":
                result = read_runbook(args.get("path", ""))
            elif name == "create_jira_ticket":
                result = create_jira_ticket(args.get("summary", ""), args.get("description", ""))
            elif name == "update_jira_ticket":
                result = update_jira_ticket(args.get("ticket_id", ""))
            else:
                result = {"error": f"unknown: {name}"}
            return JSONResponse({"result": {"content": [{"type": "text", "text": json.dumps(result, default=str)}]}})
        return JSONResponse({"error": "unknown method"})

    config = uvicorn.Config(app, host="0.0.0.0", port=8001)
    srv = uvicorn.Server(config)
    await srv.serve()


# ---------- Entry point ----------

async def main():
    if HAS_MCP_SDK:
        logger.info("Starting MCP SDK server on :8001")
        await run_sdk_server()
    else:
        logger.info("Starting FastAPI fallback MCP server on :8001")
        await run_fastapi_fallback()


if __name__ == "__main__":
    import asyncio
    asyncio.run(main())
